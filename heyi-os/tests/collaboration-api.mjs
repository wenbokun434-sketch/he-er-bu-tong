import assert from "node:assert/strict";
import { activeVotes, profileStamp, topicStatus } from "../lib/collaboration.ts";
const base = process.env.HEYI_TEST_URL || "http://127.0.0.1:4173";
if (!["127.0.0.1", "localhost"].includes(new URL(base).hostname)) throw new Error("验收写入只允许本地预览，不向线上写入测试数据。");
const read = async () => { const r = await fetch(`${base}/api/collaboration`); assert.equal(r.status, 200); return (await r.json()).state; };
let state = await read();
const initialHistoryLength = state.history.length;
async function post(actorKey, kind, payload, expected = 201) {
  const response = await fetch(`${base}/api/collaboration`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ caseId:'openair', actorKey, kind, expectedRevision: state.revision, ...payload, ...(kind==='proposal'?{details:{responsible:'三方代表',action:payload.text,timing:'24 小时内',conditions:'仅适用于本议题的试点',review:'三方共同复核，可暂停后续执行'}}:{}) }) });
  const body = await response.json(); assert.equal(response.status, expected, JSON.stringify(body));
  if (response.ok) state = body.state;
  return body;
}
const title = `验收议题 ${Date.now()}`;
await post("coordinator", "topic", { title, description: "本地自动验收，不是正式项目数据" });
const id = state.topics.at(-1).id;
const topic = () => state.topics.find(item => item.id === id);
const status = () => topicStatus(topic(), state).key;
await post("coordinator", "profile", { shareConfirmed: true, profile: state.profiles.hospital }, 403);
await post("hospital", "profile", { shareConfirmed: false, profile: state.profiles.hospital }, 400);
await post("coordinator", "proposal", { topicId: id, text: "双人审批，24 小时复审，原始数据本地留存。", reason: "" });
assert.equal(status(), "pending");
const vote = (key, choice, note = "") => post(key, "vote", { topicId: id, proposalId: topic().proposal.id, profileStamp: profileStamp(state), choice, note });
await post("coordinator", "vote", { topicId: id, proposalId: topic().proposal.id, profileStamp: profileStamp(state), choice: "accept", note: "" }, 403);
await vote("research", "accept");
await vote("hospital", "object", "需要社区代表复审权。"); assert.equal(status(), "conflict");
await vote("compliance", "info", "需要明确访问期限。");
await vote("hospital", "conditional", "加入社区复审权。"); assert.equal(status(), "information");
await vote("compliance", "accept"); assert.equal(status(), "conditional");
await post("hospital", "proposal", { topicId: id, text: "双人审批，24 小时复审，社区代表有复审与暂停权，原始数据本地留存。", reason: "纳入医院提出的社区复审条件。" });
assert.equal(Object.keys(activeVotes(topic(), state)).length, 0); assert.equal(topic().proposal.version, 2);
for (const key of ["research", "hospital", "compliance"]) await vote(key, "accept");
assert.equal(status(), "agreed");
state = await read(); assert.equal(status(), "agreed");
const beforeChat = state.revision;
await fetch(`${base}/api/messages`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ caseId:'openair', actorKey:'coordinator', content: "本地验收：聊天不会自动确认方案。" }) });
state = await read(); assert.equal(state.revision, beforeChat);
await post("hospital", "profile", { shareConfirmed: true, profile: { ...state.profiles.hospital, concern: "本地验收：新增社区担忧" } });
assert.equal(status(), "pending");
const revision = state.revision;
await post("research", "vote", { topicId: id, proposalId: topic().proposal.id, profileStamp: profileStamp(state), choice: "accept", note: "", expectedRevision: revision - 1 }, 409);
const beforeRace = state.revision;
const request = actorKey => fetch(`${base}/api/collaboration`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ caseId:'openair', actorKey, kind: "vote", topicId: id, proposalId: topic().proposal.id, profileStamp: profileStamp(state), expectedRevision: beforeRace, choice: "accept", note: "并发验收" }) });
const race = await Promise.all([request("research"), request("compliance")]);
assert.deepEqual(race.map(r => r.status).sort(), [201, 409]);
state = await read(); assert.equal(state.history.length, initialHistoryLength + 13); assert.equal(state.revision, beforeRace + 1);
console.log("PASS: 共享立场、提案修订、四种反馈、三方共识、复核、历史、重载、聊天隔离及并发保护。");
